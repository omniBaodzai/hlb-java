package variable;

public class InBienRaManHinh
{
    public static void main(String[] args)
    {
        int a = 100, b = 200, c = 300;
        System.out.println(a + " " + b + " " + c);
        // a + " " => 100 từ int chuyển thành chuỗi, do + với " "
        // kết quả là một chuỗi: 100 200 300
    }
}

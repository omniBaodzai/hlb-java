package variable;

public class DoChinhXac
{
    public static void main(String[] args)
    {
        // In ra 4 chữ số đằng sau dấu phẩy
        double soThuc = 3.1415978;
        System.out.printf("%.4f\n", soThuc); // 3.1416

        double a = 2.31452;
        double b = 3.1572;
        System.out.printf("%.2f %.3f\n", a, b); // 2.31 3.157

        System.out.print("Ket thuc!!!");
    }
}
